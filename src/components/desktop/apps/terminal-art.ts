// Splits text into lines of at most `width` characters, breaking between words where it can
function wrap(text: string, width: number) {
  return text.split('\n').flatMap((paragraph) => {
    const lines: string[] = []
    let line = ''
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      for (let rest = word; rest; ) {
        const room = line ? width - line.length - 1 : width
        if (rest.length <= room) {
          line = line ? `${line} ${rest}` : rest
          rest = ''
        } else if (line) {
          lines.push(line)
          line = ''
        } else {
          lines.push(rest.slice(0, width))
          rest = rest.slice(width)
        }
      }
    }
    lines.push(line)
    return lines
  })
}

/** A cow saying `message`, in a speech bubble, as cowsay draws it. */
export function cowsay(message: string, width = 36) {
  const lines = wrap(message.replace(/\t/g, '  '), width)
  const longest = Math.max(...lines.map((line) => line.length))
  const bubble =
    lines.length === 1
      ? [`< ${lines[0]} >`]
      : lines.map((line, index) => {
          const [left, right] = index === 0 ? ['/', '\\'] : index === lines.length - 1 ? ['\\', '/'] : ['|', '|']
          return `${left} ${line.padEnd(longest)} ${right}`
        })
  return [` ${'_'.repeat(longest + 2)}`, ...bubble, ` ${'-'.repeat(longest + 2)}`, COW].join('\n')
}
